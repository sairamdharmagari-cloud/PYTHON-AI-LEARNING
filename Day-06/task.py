# even or odd
number = int(input("Enter a number: "))

if number % 2 == 0:
    print("Even Number")
else:
    print("Odd Number")

# +ve or -ve
number = int(input("Enter a number: "))

if number >= 0:
    print("Positive Number")
else:
    print("Negative Number")

#pass or fail
marks = int(input("Enter your marks: "))

if marks >= 35:
    print("Pass")
else:
    print("Fail")