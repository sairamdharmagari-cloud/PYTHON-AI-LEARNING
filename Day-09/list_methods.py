# append() 
# Adds an item at the end:
names = ["Sairam", "Rahul", "Arjun"]
names.append("Kiran")
print(names)

#insert()
#Adds an item at a particular position:
names.insert(1, "Ravi")
print(names)

#Removing Elements
names = ["Sairam", "Rahul", "Arjun", "Kiran"]
names.remove("Rahul")
print(names)

#List Length
marks = [90, 85, 78, 92, 88]
print(len(marks))